/// =======================================================================
/// مكتبة المكونات (Component Catalog) — قلب توسعة التطبيق
/// =======================================================================
/// كل عنصر هنا هو "قالب" (Blueprint) لمكون كهربائي. لإضافة مكون جديد
/// للتطبيق مستقبلاً يكفي إضافة سطر جديد هنا (وربما رسّام مخصص اختياري)
/// دون الحاجة لتعديل محرك المحاكاة أو الواجهة أو إعادة بناء التطبيق.
///
/// الجهود المتعددة (12V/24V/48V/110/220/230/380/400V) والتردد وعدد الأطوار
/// تُضبط كخصائص (properties) قابلة للتعديل على نفس مصدر الطاقة بدل تكرار
/// عشرات الأنواع — هذا تصميم احترافي معياري (Data-Driven).
List<TerminalDef> _twoPin({TerminalKind left = TerminalKind.generic, TerminalKind right = TerminalKind.generic}) => [
      TerminalDef(id: 'a', label: 'A', kind: left, anchor: const Offset(0, 0.5)),
      TerminalDef(id: 'b', label: 'B', kind: right, anchor: const Offset(1, 0.5)),
    ];

List<TerminalDef> _polePins(int poles) {
  final list = <TerminalDef>[];
  for (var i = 0; i < poles; i++) {
    final y = (i + 1) / (poles + 1);
    list.add(TerminalDef(id: 'com$i', label: 'COM${i + 1}', kind: TerminalKind.phase, anchor: Offset(0, y)));
    list.add(TerminalDef(id: 't$i', label: 'T${i + 1}', kind: TerminalKind.phase, anchor: Offset(1, y)));
  }
  return list;
}

